///////////////////////////////////////////////////////////////////////////////
// eth_rx_cksum_basic_seq.sv — minimal stimulus sequences.
//
// The sequences operate directly on the env's APB + MII tasks rather than
// through a conventional sequencer/driver pair — the block's stimulus
// surface is small enough that the extra UVC layer wouldn't pay for itself
// in this context.
//
// Canonical pre-built IPv4/UDP frame used by the smoke sequence. The
// random / protocol-mix sequences are left as stubs for the verification
// team to flesh out alongside the coverage model.
///////////////////////////////////////////////////////////////////////////////

class eth_rx_cksum_basic_seq extends uvm_sequence;
  `uvm_object_utils(eth_rx_cksum_basic_seq)

  eth_rx_cksum_env env;

  function new(string name = "eth_rx_cksum_basic_seq");
    super.new(name);
  endfunction

  task body();
    logic [31:0] val;

    // Smoke: read ID + configure CTRL.
    env.apb_read(OFF_ID, val);
    if (val !== CKSUM_ID_VALUE)
      `uvm_error("ID", $sformatf("ID mismatch: got 0x%08h", val))

    // Enable with MODE = DROP_NEW, IRQ off.
    env.apb_write(OFF_CTRL, 32'h0000_0003);
    repeat (10) @(posedge env.cfg.vif.pclk);

    begin
      // One pre-built IPv4/UDP frame (scapy-generated bytes: same frame as
      // cocotb test_ipv4_single_good). Checksums match the wire.
      byte unsigned frame[47];
      frame = '{
        8'h00, 8'h11, 8'h22, 8'h33, 8'h44, 8'h55,   // dst MAC
        8'haa, 8'hbb, 8'hcc, 8'hdd, 8'hee, 8'hff,   // src MAC
        8'h08, 8'h00,                                // EtherType IPv4
        8'h45, 8'h00, 8'h00, 8'h21, 8'h00, 8'h01,   // IP: ver/ihl, TOS, len, ID
        8'h00, 8'h00, 8'h40, 8'h11, 8'h66, 8'hc9,   // flags/frag, TTL, proto, cksum
        8'h0a, 8'h00, 8'h00, 8'h01,                 // src IP 10.0.0.1
        8'h0a, 8'h00, 8'h00, 8'h02,                 // dst IP 10.0.0.2
        8'h04, 8'hd2, 8'h16, 8'h2e,                 // UDP src/dst port
        8'h00, 8'h0d, 8'h8c, 8'hff,                 // UDP len, cksum
        8'h68, 8'h65, 8'h6c, 8'h6c, 8'h6f           // "hello"
      };

      env.mii_send_frame(frame);
    end
    repeat (40) @(posedge env.cfg.vif.pclk);

    env.apb_read(OFF_IP_GOOD_COUNT, val);
    if (val !== 32'd1)
      `uvm_error("IP_GOOD",
                 $sformatf("IP_GOOD_COUNT expected 1, got %0d", val))

    env.apb_read(OFF_L4_GOOD_COUNT, val);
    if (val !== 32'd1)
      `uvm_error("L4_GOOD",
                 $sformatf("L4_GOOD_COUNT expected 1, got %0d", val))
  endtask
endclass
